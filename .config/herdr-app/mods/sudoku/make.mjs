// Makes new rated puzzles in node, which runs the solver ~12× faster than Herdr's engine.
//   node make.mjs <tier> [count] [hints]   print [{puz, sol, se, stuck, rank, delta}] as JSON (the app calls this)
//                                          hints: digits to add (+) or hide (-) after making; rank: level after that
//   node make.mjs --pool [count]           rebuild puzzles.js, the fallback pool and guide examples (default 60)
import { writeFileSync } from "node:fs";
import { make, adjustHints, TIERS } from "./solver.js";

const [what, n = what === "--pool" ? "60" : "1", h = "0"] = process.argv.slice(2);
const count = Math.min(Math.max(parseInt(n, 10) || 1, 1), 300);
const hints = Math.min(Math.max(parseInt(h, 10) || 0, -81), 81);
const fresh = (level, k) => {
  const out = [], seen = new Set();
  while (out.length < k) {
    const g = make(level), key = g.puz.join("");
    if (g.offTier || seen.has(key)) continue;
    seen.add(key);
    out.push(g);
  }
  return out;
};

if (what === "--pool") {
  const pool = Object.fromEntries(Object.keys(TIERS).map((level) =>
    [level, fresh(level, count).map((g) => [g.puz.join(""), g.sol.join(""), g.se, g.stuck ? 1 : 0])]));
  writeFileSync(new URL("./puzzles.js", import.meta.url),
    `// Generated by make.mjs --pool: ${count} rated puzzles per tier as [puzzle, solution, SE rating, needs patterns past SE 4.4], 0 = blank.\n` +
    `export const POOL = ${JSON.stringify(pool, null, 1)};\n`);
} else if (TIERS[what]) {
  console.log(JSON.stringify(fresh(what, count).map((g) => adjustHints(g, hints)).map((g) => (
    { puz: g.puz.join(""), sol: g.sol.join(""), se: g.se, stuck: g.stuck, rank: g.rank, delta: g.delta }))));
} else {
  console.error(`usage: node make.mjs <${Object.keys(TIERS).join("|")}> [count] [hints] | --pool [count]`);
  process.exit(2);
}
